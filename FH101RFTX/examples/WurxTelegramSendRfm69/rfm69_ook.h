/**
 * @file rfm69_ook.h
 * @brief Minimal RFM69HCW driver for raw OOK bit stream transmission.
 *
 * The RFM69HCW (SX1231H) transmits raw OOK bit streams: the bytes written
 * into the FIFO are shifted out at the bit rate programmed in RegBitrate,
 * MSB first, one bit = carrier on for a logical 1 and carrier off for a
 * logical 0. The chip generates the bit timing itself, so the chip rate is as
 * exact as the module crystal.
 *
 * The OOK modulator is driven from the FIFO, which requires PACKET mode
 * (DataMode = 00). Continuous mode (DataMode = 10) is NOT usable here: the
 * datasheet states that in continuous mode the data goes through the
 * DIO2/DATA pin and "the FIFO and packet handler are thus inactive", so every
 * FIFO write is discarded and the PA only emits a flat carrier.
 *
 * To make the packet handler transparent, PayloadLength is 0 (unlimited
 * length packet format), the preamble length is 0 and SyncOn is 0, so nothing
 * is added to or removed from the FIFO contents.
 *
 * This is exactly what the FH101RF wake-up telegram needs: the telegram
 * generated by the FH101RFTX library is a bit packed chip stream, MSB first,
 * and can be written into the FIFO unchanged.
 *
 * Wiring (Adafruit Feather M0 RFM69HCW, on-board module):
 *   CS    -> D8
 *   RESET -> D4
 *   SCK/MOSI/MISO -> hardware SPI (D24/D23/D22)
 *   DIO0  -> D3 (not used here)
 *
 * The register set is reduced to what raw OOK transmission needs.
 */
#ifndef RFM69_OOK_H_
#define RFM69_OOK_H_

#include <stdint.h>
#include <stdbool.h>

/* -------------------------------------------------------------------------
 * hardware configuration
 * ---------------------------------------------------------------------- */

/** chip select of the on-board RFM69HCW (Feather M0 RFM69HCW: D8) */
#ifndef RFM69_CS_PIN
#define RFM69_CS_PIN 8
#endif

/** reset of the on-board RFM69HCW (Feather M0 RFM69HCW: D4), -1 = not wired */
#ifndef RFM69_RESET_PIN
#define RFM69_RESET_PIN 4
#endif

/* -------------------------------------------------------------------------
 * RFM69 register map (SX1231 / RFM69, only the used registers)
 * ---------------------------------------------------------------------- */
#define RFM69_REG_FIFO          0x00
#define RFM69_REG_OPMODE        0x01
#define RFM69_REG_DATAMODUL     0x02
#define RFM69_REG_BITRATEMSB    0x03
#define RFM69_REG_BITRATELSB    0x04
#define RFM69_REG_FRFMSB        0x07
#define RFM69_REG_FRFMID        0x08
#define RFM69_REG_FRFLSB        0x09
#define RFM69_REG_VERSION       0x10
#define RFM69_REG_PALEVEL       0x11
#define RFM69_REG_PARAMP        0x12
#define RFM69_REG_OCP           0x13
#define RFM69_REG_DIOMAPPING1   0x25
#define RFM69_REG_DIOMAPPING2   0x26
#define RFM69_REG_IRQFLAGS1     0x27
#define RFM69_REG_IRQFLAGS2     0x28
#define RFM69_REG_PREAMBLEMSB   0x2C
#define RFM69_REG_PREAMBLELSB   0x2D
#define RFM69_REG_SYNCCONFIG    0x2E
#define RFM69_REG_SYNCVALUE1    0x2F
#define RFM69_REG_PACKETCONFIG1 0x37
#define RFM69_REG_PAYLOADLENGTH 0x38
#define RFM69_REG_NODEADRS      0x39
#define RFM69_REG_BROADCASTADRS 0x3A
#define RFM69_REG_AUTOMODES     0x3B
#define RFM69_REG_FIFOTHRESH    0x3C
#define RFM69_REG_PACKETCONFIG2 0x3D

/* RegOpMode: mode bits 4:2 */
#define RFM69_OPMODE_STANDBY    0x04
#define RFM69_OPMODE_TX         0x0C

/* RegDataModul bits 6:5 DataMode: 00 = packet, 01 = reserved,
   10 = continuous mode with bit synchronizer, 11 = continuous without.
   bits 4:3 ModulationType: 00 = FSK, 01 = OOK.
   bits 1:0 ModulationShaping: 00 = no shaping (sharpest OOK edges).

   IMPORTANT: OOK has to run in PACKET mode, not in continuous mode.

   Datasheet section 5.4.1: "in Continuous mode the NRZ data to (from) the
   (de)modulator is directly accessed by the uC on the bidirectional
   DIO2/DATA pin. The FIFO and packet handler are thus inactive."

   So with DataMode = 10 the FIFO is switched off completely: every byte
   written to RegFifo is discarded, the modulator never receives any data and
   the PA emits a flat, unmodulated carrier. This was measured, not assumed -
   a FIFO round trip returns 0 of 8 bytes in continuous mode and 8 of 8 in
   packet mode, in all five chip modes (sleep, standby, FS, TX, RX).

   With DataMode = 00 (packet mode) plus PayloadLength = 0 the packet handler
   runs in unlimited length mode, and with PreambleLength = 0 and SyncOn = 0
   it adds nothing at all, so the FIFO bytes reach the modulator unchanged. */
#define RFM69_DATAMODUL_OOK         0x08

/* RegPaRamp bits 3:0 = PA ramp time.
   There is NO "ramp off" setting: 0x00 is the SLOWEST ramp (3.4 ms), not the
   fastest. The shortest ramp the SX1231 offers is 10 us at 0x0F, which is the
   widest bandwidth and the sharpest OOK edges this chip can produce.
   Reset default is 0x09 = 40 us. */
#define RFM69_PARAMP_3400US 0x00
#define RFM69_PARAMP_2000US 0x01
#define RFM69_PARAMP_1000US 0x02
#define RFM69_PARAMP_500US  0x03
#define RFM69_PARAMP_250US  0x04
#define RFM69_PARAMP_125US  0x05
#define RFM69_PARAMP_100US  0x06
#define RFM69_PARAMP_62US   0x07
#define RFM69_PARAMP_50US   0x08
#define RFM69_PARAMP_40US   0x09
#define RFM69_PARAMP_31US   0x0A
#define RFM69_PARAMP_25US   0x0B
#define RFM69_PARAMP_20US   0x0C
#define RFM69_PARAMP_15US   0x0D
#define RFM69_PARAMP_12US   0x0E
#define RFM69_PARAMP_10US   0x0F

/**
 * @brief PA ramp time, default: shortest possible (10 us)
 *
 * For OOK at 33096 chip/s one chip lasts 30.2 us, so a 10 us ramp already
 * occupies a third of a chip. Anything slower than about 0x0A (31 us) is
 * longer than a single chip and would smear the envelope beyond recognition,
 * which is why slower values are rejected at compile time.
 *
 * Note the direction: the register value gets SMALLER as the ramp gets LONGER.
 */
#ifndef RFM69_PARAMP
#define RFM69_PARAMP RFM69_PARAMP_10US
#endif

#if (RFM69_PARAMP < RFM69_PARAMP_31US)
#error "RFM69_PARAMP is slower than one OOK chip (30.2 us), the telegram would be destroyed"
#endif

/* RegOcp: bit 4 = over current protection on, bits 3:0 = trim, 0x0A = 95 mA */
#define RFM69_OCP_ON_95MA 0x1A
#define RFM69_OCP_OFF     0x0F

/* RegDioMapping2: bits 2:0 clock output, 0x07 = off */
#define RFM69_CLKOUT_OFF 0x07

/* RegFifoThresh: bit 7 = TxStartCondition, 1 = start when FIFO not empty */
#define RFM69_FIFOTHRESH_TXSTART_FIFONOTEMPTY 0x80

/* RegIrqFlags1 */
#define RFM69_IRQFLAGS1_MODEREADY 0x80
#define RFM69_IRQFLAGS1_TXREADY   0x20
#define RFM69_IRQFLAGS1_PLLLOCK   0x10

/* RegIrqFlags2 */
#define RFM69_IRQFLAGS2_FIFOFULL     0x80
#define RFM69_IRQFLAGS2_FIFONOTEMPTY 0x40
#define RFM69_IRQFLAGS2_FIFOLEVEL    0x20
#define RFM69_IRQFLAGS2_FIFOOVERRUN  0x10
#define RFM69_IRQFLAGS2_PACKETSENT   0x08

/**
 * @brief transmit power in dBm, default 0 dBm
 *
 * The RFM69HCW module only brings the PA_BOOST output to its antenna pin, the
 * RFO (PA0) output is not connected, so PA1 (bit 6 of RegPaLevel) is used.
 * With PA1 only the output power is Pout = -18 dBm + OutputPower, which makes
 * the usable range -18 dBm (OutputPower = 0) to +13 dBm (OutputPower = 31).
 * OutputPower = dBm + 18, so 0 dBm gives 18 = 0x12 and RegPaLevel = 0x52.
 *
 * Levels above +13 dBm need the high power settings (RegTestPa1/RegTestPa2
 * plus PA2) and are not supported here. 0 dBm draws roughly 13 mA, +10 dBm
 * roughly 40 mA, both stay well below the 95 mA over current limit.
 */
#ifndef RFM69_TX_POWER_DBM
#define RFM69_TX_POWER_DBM 0
#endif

#if (RFM69_TX_POWER_DBM < -18) || (RFM69_TX_POWER_DBM > 13)
#error "RFM69_TX_POWER_DBM must be between -18 and +13 for a single PA output"
#endif

/* RegPaLevel output selection (bits 7:5) */
#define RFM69_PA_PA1_BOOST   0x40  /**< PA_BOOST output, this is the module antenna pin */

/** @brief which PA output to use, default PA1 = PA_BOOST (module antenna) */
#ifndef RFM69_PA_OUTPUT
#define RFM69_PA_OUTPUT RFM69_PA_PA1_BOOST
#endif

/** @brief RegPaLevel: selected PA output | OutputPower = dBm + 18 */
#ifndef RFM69_PA_LEVEL
#define RFM69_PA_LEVEL (RFM69_PA_OUTPUT | (RFM69_TX_POWER_DBM + 18))
#endif

/** expected content of RegVersion for an RFM69 */
#define RFM69_VERSION_EXPECTED 0x24u

/** oscillator frequency of the RFM69 in Hz */
#define RFM69_FXOSC_HZ 32000000UL

/** timeout while waiting for the FIFO to drain, in microseconds */
#define RFM69_TX_TIMEOUT_US 200000UL

/**
 * @brief CS setup time in microseconds before the first clock edge
 *
 * The RFM69 decides on the direction of an access with bit 7 of the address
 * byte. If that first bit is sampled before it is stable, a write is seen as
 * a read: the register keeps its old value and the access fails silently.
 */
#ifndef RFM69_CS_SETUP_US
#define RFM69_CS_SETUP_US 1u
#endif

/** @brief CS hold time in microseconds after the last clock edge */
#ifndef RFM69_CS_HOLD_US
#define RFM69_CS_HOLD_US 1u
#endif

/**
 * @brief reset and configure the RFM69 for OOK packet mode transmission
 * @param frequencyHz carrier frequency in Hz, e.g. 868800000
 * @param bitRateHz   chip rate in Hz, e.g. 33096
 * @retval true if the device answered with the expected version and was
 *         configured, false otherwise
 *
 * The function starts the SPI bus itself, pulses the reset line and checks
 * RegVersion. If the version does not match, it retries with a lower SPI
 * clock and finally runs a register write/read-back test, so that
 * rfm69_ook_version() and rfm69_ook_spi_ok() can be used to tell a bus
 * problem from a missing module.
 */
bool rfm69_ook_begin(uint32_t frequencyHz, uint32_t bitRateHz);

/**
 * @brief RegVersion value read by the last rfm69_ook_begin() call
 * @retval 0x24 for a working RFM69, 0x00 or 0xFF if nothing answered
 */
uint8_t rfm69_ook_version(void);

/**
 * @brief result of the register write/read-back test of rfm69_ook_begin()
 * @retval true if a register could be written and read back unchanged
 *
 * If this is true but the version is wrong, the SPI bus and the wiring are
 * fine and the module is either a different type or not an RFM69 at all.
 */
bool rfm69_ook_spi_ok(void);

/**
 * @brief SPI clock that finally worked in rfm69_ook_begin()
 * @retval clock in Hz, 0 if the bus was never initialised
 */
uint32_t rfm69_ook_spi_hz(void);

/**
 * @brief transmit a byte stream as raw OOK bit stream, blocking
 * @param data   bytes to send, MSB first, 1 = carrier on
 * @param length number of bytes
 * @retval telegram duration in microseconds, 0 if nothing was sent
 *
 * The function feeds the 66 byte FIFO while the modulator shifts the bits out
 * and returns after the last bit was transmitted and the chip is back in
 * standby mode.
 */
uint32_t rfm69_ook_send(const uint8_t *data, uint16_t length);

/**
 * @brief put the RFM69 into standby mode
 */
void rfm69_ook_standby(void);

/**
 * @brief set the transmit power at runtime
 * @param dBm output power, -18 .. +13 dBm on the PA_BOOST output
 * @retval true if the register was written and read back unchanged
 *
 * rfm69_ook_begin() programs RFM69_TX_POWER_DBM, which is a compile time
 * constant baked into rfm69_ook.cpp. This function overrides it at runtime,
 * which is needed whenever the power has to be matched to the link: a
 * receiver sitting centimetres away from the antenna is easily overloaded
 * by 0 dBm, and a wake-up receiver then detects nothing at all.
 *
 * The write is verified by reading RegPaLevel back, so a missed SPI access
 * cannot leave the module on a power level nobody expects.
 */
bool rfm69_ook_set_power_dbm(int8_t dBm);

/**
 * @brief read back RegPaLevel
 * @retval register value, e.g. 0x52 for 0 dBm on PA_BOOST
 */
uint8_t rfm69_ook_power_reg(void);

/**
 * @brief bit rate register value that was programmed by rfm69_ook_begin()
 * @retval 16 bit RegBitrate value, 0 if not configured
 */
uint16_t rfm69_ook_bitrate_reg(void);

/**
 * @brief bit rate that results from the programmed register value
 * @retval bit rate in Hz, 0 if not configured
 */
uint32_t rfm69_ook_bitrate_hz(void);

/**
 * @brief carrier frequency that results from the programmed register value
 * @retval frequency in Hz, 0 if not configured
 */
uint32_t rfm69_ook_frequency_hz(void);

#endif /* RFM69_OOK_H_ */
